const toNode = (id: string, px: number, py: number): PathNode => ({
  id,
  x: px / MAP_IMAGE.width,
  y: py / MAP_IMAGE.height,
});

const ROAD_NODES: PathNode[] = ROAD.map(([id, px, py]) => toNode(id, px, py));

// One entrance node per building, id = 'e' + building number (for example 'e23').
const ENTRANCE_NODES: PathNode[] = DESTINATIONS.map((d) => ({
  ...toNode(`e${d.number}`, d.mapX, d.mapY),
  destinationId: d.id,
}));

const pixelGap = (a: PathNode, b: PathNode) =>
  Math.hypot((a.x - b.x) * MAP_IMAGE.width, (a.y - b.y) * MAP_IMAGE.height);

// Link every building to the closest road node.
const BUILDING_LINKS: PathEdge[] = ENTRANCE_NODES.map((entrance) => {
  const nearest = ROAD_NODES.reduce((best, node) =>
    pixelGap(entrance, node) < pixelGap(entrance, best) ? node : best
  );
  return [entrance.id, nearest.id];
});

export const PATH_NODES: PathNode[] = [...ROAD_NODES, ...ENTRANCE_NODES];
export const PATH_EDGES: PathEdge[] = [...ROAD_EDGES, ...BUILDING_LINKS];